            k = slug.replace("-", "_")
            steps.append({
                "@type": "HowToStep",
                "name": s[f"help.s_{k}_h3"],
                "text": s[f"help.s_{k}_p"],
                "url": f"{url}#step-{slug}",
                "image": f"{BASE}/img/help/{ilang}/{slug}.png",
            })
